export function isAiGeneratedContent(caption: string = '', username: string = ''): { isAigc: boolean; matchedTerm?: string } {
  const textLower = `${caption || ''} ${username || ''}`.toLowerCase()
  for (const kw of AIGC_FILTER_KEYWORDS) {
    if (kw && textLower.includes(kw.toLowerCase())) {
      return { isAigc: true, matchedTerm: kw }
    }
  }
  // 額外檢查常見 AIGC Hashtag 組合
  const aigcTagRegex = /#(aiart|aivideo|aianimation|aigenerated|midjourney|stablediffusion|sora|runwayml|klingai|pikaart|aigirl|aigc|ai繪圖|ai動畫|ai影片|ai生成)\b/i
  const m = textLower.match(aigcTagRegex)
  if (m) {
    return { isAigc: true, matchedTerm: m[0] }
  }
  return { isAigc: false }
}

