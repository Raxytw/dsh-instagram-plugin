/**
 * 自動補全與同步讀取 dsh-instagram-plugin/data/config.json 的 LLM 配置，
 * 確保即使由外部模組 (如 dsh-instagram-scroll) 調用，也能準確讀取使用者在面板選擇的訂閱平台與模型 (例如 gemini-3-flash)
 */
export function resolveEffectiveLlmConfig(inputConfig?: Partial<InstagramPluginConfig>): Partial<InstagramPluginConfig> {
  const merged: Partial<InstagramPluginConfig> = { ...(inputConfig || {}) }
  if (merged.llmMode && (merged.subscriptionModel || merged.customLlmModel)) {
    return merged
  }
  try {
    const pluginRoot = dirname(dirname(dirname(fileURLToPath(import.meta.url))))
    const cfgPath = join(pluginRoot, 'data', 'config.json')
    if (existsSync(cfgPath)) {
      const diskCfg = JSON.parse(readFileSync(cfgPath, 'utf-8'))
      return {
        ...diskCfg,
        ...merged,
        llmMode: merged.llmMode || diskCfg.llmMode || 'auto',
        subscriptionProvider: merged.subscriptionProvider || diskCfg.subscriptionProvider || 'antigravity',
        subscriptionModel: merged.subscriptionModel || diskCfg.subscriptionModel || 'gemini-3-flash',
        customLlmApiBase: merged.customLlmApiBase || diskCfg.customLlmApiBase || 'https://api.deepseek.com',
        customLlmModel: merged.customLlmModel || diskCfg.customLlmModel || 'deepseek-chat',
        customLlmApiKey: merged.customLlmApiKey || diskCfg.customLlmApiKey || '',
      }
    }
  } catch {}
  return merged
}

/**
 * 依序自動探索可用之 API Key：
 * 1. 插件設定檔自定義 customLlmApiKey
 * 2. 環境變數 DEEPSEEK_API_KEY / OPENAI_API_KEY / GROQ_API_KEY / SILICONFLOW_API_KEY
 * 3. ~/.dsh/.credentials.yaml 中儲存的 DEEPSEEK_API_KEY / OPENAI_API_KEY
 * 4. 同工作區 dsh-discord-plugin 已配置的 customLlmApiKey
 */
export function resolveApiKey(config?: Partial<InstagramPluginConfig>): string {
  if (config?.customLlmApiKey && config.customLlmApiKey.trim()) {
    return config.customLlmApiKey.trim()
  }

  if (process.env.DEEPSEEK_API_KEY && process.env.DEEPSEEK_API_KEY.trim()) {
    return process.env.DEEPSEEK_API_KEY.trim()
  }
  if (process.env.OPENAI_API_KEY && process.env.OPENAI_API_KEY.trim()) {
    return process.env.OPENAI_API_KEY.trim()
  }
  if (process.env.GROQ_API_KEY && process.env.GROQ_API_KEY.trim()) {
    return process.env.GROQ_API_KEY.trim()
  }
  if (process.env.SILICONFLOW_API_KEY && process.env.SILICONFLOW_API_KEY.trim()) {
    return process.env.SILICONFLOW_API_KEY.trim()
  }

  // 嘗試從 ~/.dsh/.credentials.yaml 讀取
  try {
    const home = process.env.DSH_HOME || join(process.env.USERPROFILE || process.env.HOME || '', '.dsh')
    const credPath = join(home, '.credentials.yaml')
    if (existsSync(credPath)) {
      const content = readFileSync(credPath, 'utf-8')
      const m1 = content.match(/DEEPSEEK_API_KEY:\s*([^\r\n#]+)/)
      if (m1 && m1[1] && m1[1].trim()) return m1[1].trim()
      const m2 = content.match(/OPENAI_API_KEY:\s*([^\r\n#]+)/)
      if (m2 && m2[1] && m2[1].trim()) return m2[1].trim()
    }
  } catch {}

  // 嘗試從相鄰的 dsh-discord-plugin/data/config.json 讀取共享設定
  try {
    const pluginRoot = dirname(dirname(dirname(fileURLToPath(import.meta.url))))
    const discordCfgPath = join(dirname(pluginRoot), 'dsh-discord-plugin', 'data', 'config.json')
    if (existsSync(discordCfgPath)) {
      const dCfg = JSON.parse(readFileSync(discordCfgPath, 'utf-8'))
      if (dCfg?.customLlmApiKey && String(dCfg.customLlmApiKey).trim()) {
        return String(dCfg.customLlmApiKey).trim()
      }
    }
  } catch {}

  return ''
}

